import fs from 'fs';
import path from 'path';

const portfolioDir = path.resolve('src/assets/portfolio');
const dataFile = path.resolve('public/data/portfolio.json');
const outDir = path.resolve('src/generated');
const outFile = path.join(outDir, 'imageMap.ts');

if (!fs.existsSync(portfolioDir)) {
  console.error('[image-registry] src/assets/portfolio/ not found');
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(dataFile, 'utf-8'));

function safeIdent(filename) {
  return 'img_' + filename.replace(/[^a-zA-Z0-9]/g, '_');
}

function extractImagePaths(obj) {
  const paths = new Set();
  function walk(val) {
    if (!val) return;
    if (typeof val === 'string' && val.startsWith('/assets/')) {
      paths.add(val);
      return;
    }
    if (Array.isArray(val)) { val.forEach(walk); return; }
    if (typeof val === 'object') { Object.values(val).forEach(walk); }
  }
  walk(obj);
  return [...paths];
}

const imagePaths = extractImagePaths(data);
const imports = [];
const entries = [];

for (const imgPath of imagePaths) {
  const filename = imgPath.replace('/assets/', '');
  const filePath = path.join(portfolioDir, filename);
  if (!fs.existsSync(filePath)) {
    console.warn(`[image-registry] WARNING: ${imgPath} referenced in JSON but not found in portfolio dir`);
    continue;
  }
  const ident = safeIdent(filename);
  imports.push(`import ${ident} from '../assets/portfolio/${filename}';`);
  entries.push(`  ${JSON.stringify(imgPath)}: ${ident}`);
}

const content = `// Auto-generated by scripts/build-image-registry.mjs — DO NOT EDIT
${imports.join('\n')}

const imageMap: Record<string, any> = {
${entries.join(',\n')}
};

export default imageMap;
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, content);
console.log(`[image-registry] Generated with ${entries.length} referenced images → src/generated/imageMap.ts`);
